const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {insertSecretariaEscolar}=require('../lib/secretaria-escolar');
const {insertCuidadorSocial}=require('../lib/cuidador-social');
const art=require('../lib/secretaria-escolar-art.json');
assert.ok(art.startsWith('data:image/svg+xml;base64,'));
const src=Buffer.from(art.split(',')[1],'base64').toString('utf8');
assert.match(src,/640 960/);
const base='<html><head></head><body><div id="especificas"><a data-jr-card="servicosgerais" href="/api/area-entry?area=servicosgerais">Serviços</a></div></body></html>';
const withCs=insertCuidadorSocial(base);
const html=insertSecretariaEscolar(withCs);
assert.equal((html.match(/data-jr-card="secretariaescolar"/g)||[]).length,1);
assert.match(html,/href="\/api\/area-entry\?area=secretariaescolar"/);
assert.match(html,/jr-uniform-access-btn/);
assert.equal(insertSecretariaEscolar(html),html);
const api=fs.readFileSync(path.join(__dirname,'..','api/area-entry.js'),'utf8');
const ent=fs.readFileSync(path.join(__dirname,'..','api/_entitlement.js'),'utf8');
const inject=fs.readFileSync(path.join(__dirname,'..','api/inject-quimica.js'),'utf8');
assert.match(api,/secretariaescolar/);
assert.match(ent,/secretariaescolar/);
assert.match(inject,/insertSecretariaEscolar\(html\)/);
console.log('OK: card de Secretaria Escolar Projeto 1 + URL do Projeto 2');
